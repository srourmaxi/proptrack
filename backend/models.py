class Valuacion(Base):
    __tablename__ = "valuaciones"
    id = Column(Integer, primary_key=True, index=True)
    propiedad_id = Column(Integer, nullable=False)
    fecha = Column(String, nullable=False)
    valor_usd = Column(Float, nullable=False)
    fuente = Column(String, default="manual")
    estado_obra = Column(String, default='terminado')
    notas = Column(Text)

class Alquiler(Base):
    __tablename__ = "alquileres"
    id = Column(Integer, primary_key=True, index=True)
    propiedad_id = Column(Integer, nullable=False)
    fecha_desde = Column(String, nullable=False)
    fecha_hasta = Column(String)
    monto_usd = Column(Float, nullable=False)
    inquilino = Column(String)
    notas = Column(Text)

class MovimientoFinanciero(Base):
    __tablename__ = "movimientos_financieros"
    id = Column(Integer, primary_key=True, index=True)
    propiedad_id = Column(Integer, nullable=False)
    operacion = Column(String, nullable=False)
    tipo = Column(String, nullable=False)
    concepto = Column(String)
    fecha_vencimiento = Column(String)
    fecha_pago = Column(String)
    monto = Column(Float, default=0)
    moneda = Column(String, default='USD')
    cotizacion = Column(Float, default=1)
    monto_usd = Column(Float, default=0)
    pagado = Column(Boolean, default=False)
    notas = Column(Text)

